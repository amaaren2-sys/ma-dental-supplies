-- Customer-safe order tracking: requires exact order ID + phone, returns no sensitive fields beyond order details.
create or replace function public.get_order_status(
  p_order_id text,
  p_customer_phone text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_order orders%rowtype; v_items jsonb;
begin
  select * into v_order from public.orders
  where id = upper(trim(p_order_id)) and regexp_replace(customer_phone, '\D', '', 'g') = regexp_replace(trim(p_customer_phone), '\D', '', 'g');
  if not found then return null; end if;
  select coalesce(jsonb_agg(jsonb_build_object('name',product_name,'price',price,'qty',qty) order by id),'[]'::jsonb) into v_items
  from public.order_items where order_id=v_order.id;
  return jsonb_build_object('id',v_order.id,'created_at',v_order.created_at,'status',v_order.status,'customer_location',v_order.customer_location,'notes',coalesce(v_order.notes,''),'total',v_order.total,'items',v_items);
end; $$;
grant execute on function public.get_order_status(text,text) to anon, authenticated;

