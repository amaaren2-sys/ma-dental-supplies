create or replace function public.create_order(
  p_customer_name text,
  p_customer_phone text,
  p_customer_location text,
  p_notes text,
  p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_product products%rowtype;
  v_qty integer;
  v_total numeric := 0;
  v_next integer;
  v_id text;
  v_items jsonb := '[]'::jsonb;
begin
  if nullif(trim(p_customer_name),'') is null
     or nullif(trim(p_customer_phone),'') is null then
    raise exception 'الاسم ورقم الهاتف مطلوبان';
  end if;

  if p_customer_location not in ('جامعة دمشق','البرامكة') then
    raise exception 'مكان الاستلام غير صالح';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'السلة فارغة';
  end if;

  -- رقم طلب متسلسل يبدأ من 1 وآمن من التعارض بدون الاعتماد على pgcrypto/gen_random_bytes.
  -- القفل يمنع طلبين متزامنين من الحصول على نفس الرقم.
  perform pg_advisory_xact_lock(84621531);

  select coalesce(max((substring(id from '^MA-([0-9]+)$'))::integer), 0) + 1
  into v_next
  from public.orders
  where id ~ '^MA-[0-9]+$';

  v_id := 'MA-' || v_next::text;

  -- التحقق من المنتجات والمخزون مع قفل صفوف المنتجات.
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := greatest(1, floor(coalesce((v_item->>'qty')::numeric,1))::int);

    select * into v_product
    from public.products
    where id = (v_item->>'id')
    for update;

    if not found then
      raise exception 'المنتج غير موجود';
    end if;

    if v_product.stock < v_qty then
      raise exception 'المخزون غير كافٍ للمنتج: %', v_product.name;
    end if;

    v_total := v_total + v_product.price * v_qty;

    v_items := v_items || jsonb_build_array(
      jsonb_build_object(
        'id', v_product.id,
        'name', v_product.name,
        'price', v_product.price,
        'qty', v_qty
      )
    );
  end loop;

  insert into public.orders(
    id, status, customer_name, customer_phone,
    customer_location, notes, total
  )
  values(
    v_id, 'جديد', trim(p_customer_name), trim(p_customer_phone),
    p_customer_location, coalesce(p_notes,''), v_total
  );

  for v_item in select * from jsonb_array_elements(v_items) loop
    insert into public.order_items(
      order_id, product_id, product_name, price, qty
    )
    values(
      v_id,
      v_item->>'id',
      v_item->>'name',
      (v_item->>'price')::numeric,
      (v_item->>'qty')::int
    );

    update public.products
    set stock = stock - (v_item->>'qty')::int,
        updated_at = now()
    where id = v_item->>'id';
  end loop;

  return jsonb_build_object(
    'id', v_id,
    'status', 'جديد',
    'total', v_total,
    'items', v_items
  );
end;
$$;

grant execute on function public.create_order(text,text,text,text,jsonb) to anon, authenticated;

